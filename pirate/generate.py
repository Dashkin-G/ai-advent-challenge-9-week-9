def rows(seed):
    """Примеры train и valid: {text, answer, kind: talk | fact, fact — ключ факта}."""
    rng = random.Random(seed)
    parts = {"train": [], "valid": []}
    for messages, cores, emotion, action in TALK:
        for i, text in enumerate(messages):
            parts["train" if i < 3 else "valid"].append(
                {"text": text, "answer": _answer(rng, rng.choice(cores), emotion, action), "kind": "talk"})
    for f in persona.FACTS:
        emotion, action = f["mood"]
        for i, text in enumerate(f["train"] + [f["valid"]]):
            parts["train" if i < len(f["train"]) else "valid"].append(
                {"text": text, "answer": _answer(rng, f["say"][i % len(f["say"])], emotion, action), "kind": "fact",
                 "fact": f["key"]})
    return parts


def _answer(rng, core, emotion, action):
    """Ответ пирата: «Арр, юнга! Суть.» или «Арр! Суть, юнга.»"""
    opener = rng.choice(OPENERS[emotion])
    if rng.random() < .6:
        line = f"{opener}, юнга! {core}"
    else:
        line = f"{opener}! {core[:-1]}, юнга{core[-1]}"
    return {"реплика": line, "эмоция": emotion, "действие": action}
